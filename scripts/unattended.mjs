// What a run without the plugin reads from the repo (docs/ai-layout.md §Runs without the plugin), on when
// ai/kit/config.json has "unattended": true: the conventions snapshot, ai/kit/check.sh and one CLAUDE.md line.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LINE = "Before writing code, read `ai/kit/conventions/`.";
const HEAD = /^<!-- generated by ai-kit \S+ from conventions\/\S+, never edit; sha256 ([0-9a-f]{64}) -->\n\n/;
const SYNC = "fix: node <plugin>/scripts/kit.mjs sync";
// a diff of the index finds nothing under check.sh, and --staged asks a script for that diff; other index reads hold,
// a clean clone's index being HEAD
const STAGED = "diff[^|;&]*--cached|--staged";
// what ai/kit/pre-commit.sh may call, in every runner that sources it; githooks/pre-commit holds the same
export const HELPERS = `quiet() {
  out=$("$@" 2>&1); rc=$?
  if [ $rc -ne 0 ]; then printf '%s\\n' "$out"
  else
    n=$(printf '%s\\n' "$out" | grep -c '^!')
    [ "$n" -gt 0 ] && echo "warn: $n warning(s) from: $* (run it alone for details)"
  fi
  return $rc
}
# the files to check: AI_KIT_FILES when ai/kit/check.sh set it, else the staged ones
changed() {
  if [ -n "\${AI_KIT_FILES+set}" ]; then [ -z "$AI_KIT_FILES" ] || printf '%s\\n' "$AI_KIT_FILES"
  else git diff --cached --name-only --diff-filter=ACMR; fi
}
# what a check that reads the diff passes to git diff, unquoted; ai/kit/check.sh replaces it with its range
export AI_KIT_RANGE=--cached
`;
const CHECK_SH = `#!/usr/bin/env sh
# Generated by ai-kit, never edit. Runs ai/kit/pre-commit.sh on the files changed from a base ref, for a gate with no
# plugin: sh ai/kit/check.sh origin/main. It only reads HEAD and the index, so a killed run leaves nothing to restore;
# a project check that writes the index skips itself here (docs/ai-layout.md).
base="$1"
[ -n "$base" ] || { echo "usage: sh ai/kit/check.sh <base-ref>"; exit 2; }
# AI_KIT_RANGE expands unquoted: split words make git diff fail, and a check piping it would read that as no change
case "$base" in *[[:space:]]*) echo "check blocked: a base ref with a space"; exit 2 ;; esac
cd "$(git rev-parse --show-toplevel)" || exit 1
[ -f ai/kit/pre-commit.sh ] || { echo "check blocked: ai/kit/pre-commit.sh is missing"; exit 1; }
# bash as sh carries on past a syntax error in a sourced file, which would reach the exit 0 below
sh -n ai/kit/pre-commit.sh || { echo "check blocked: ai/kit/pre-commit.sh does not parse"; exit 1; }
# a gate on a staged diff would find nothing here and pass without checking anything
if grep -v '^[[:space:]]*#' ai/kit/pre-commit.sh | grep -qE -e '${STAGED}'; then
  echo "check blocked: ai/kit/pre-commit.sh reads the staged diff; use changed and \\$AI_KIT_RANGE (the plugin's template)"
  exit 1
fi
# not exported: a list over the kernel's limit would make every command it runs fail, and a failed gate reads as a pass
AI_KIT_FILES="$(git -c core.quotePath=false diff --name-only --diff-filter=ACMR "$base...HEAD")" || {
  echo "check blocked: no diff from $base (a shallow clone needs the base's history)"
  exit 1
}
${HELPERS}AI_KIT_RANGE="$base...HEAD"
# shellcheck source=/dev/null
. ai/kit/pre-commit.sh
echo "checked $(changed | grep -c .) file(s) from $base"
exit 0
`;

const sha = (t) => createHash("sha256").update(t).digest("hex");
const read = (p) => (existsSync(p) ? readFileSync(p, "utf8").replace(/\r\n/g, "\n") : null);
const config = (root) => {
  try {
    return JSON.parse(read(join(root, "ai", "kit", "config.json")));
  } catch {
    return null;
  }
};

// general.md, the config's files, and each file's "Adds to" list, followed through; plugin docs keep the kit's name
const bodies = (root, kit) => {
  const out = new Map();
  const visit = (n) => {
    const t = read(join(kit, "conventions", n));
    if (t === null || out.has(n)) return;
    out.set(n, t.replace(/`docs\//g, "`ai-kit/docs/"));
    const adds = t.match(/Adds to ([^\n]*(?:\n[^\n]+)*)/)?.[1] ?? "";
    for (const [, f] of adds.matchAll(/`([\w-]+\.md)`/g)) visit(f);
  };
  visit("general.md");
  const convs = config(root)?.conventions;
  for (const c of Array.isArray(convs) ? convs : []) visit(`${c}.md`);
  return out;
};
const files = (dir) =>
  existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true }).filter((e) => e.isFile()).map((e) => e.name)
    : [];
const generated = (dir) => files(dir).filter((f) => HEAD.test(read(join(dir, f))));
const intact = (t) => t.match(HEAD)?.[1] === sha(t.replace(HEAD, ""));
const hasLine = (t) => t?.split("\n").some((l) => l.trim() === LINE) ?? false;

// null when the project has not opted in, else how many files it left; a current copy stays, whatever kit wrote it
export function syncSnapshot(root, kit) {
  if (config(root)?.unattended !== true) return null;
  let left = 0;
  const version = JSON.parse(read(join(kit, ".claude-plugin", "plugin.json"))).version;
  const dir = join(root, "ai", "kit", "conventions");
  mkdirSync(dir, { recursive: true });
  const want = bodies(root, kit);
  for (const [n, body] of want) {
    const p = join(dir, n);
    const t = read(p);
    if (t !== null && !HEAD.test(t)) {
      console.log(`! ai/kit/conventions/${n} is not a generated copy: left as it is`);
      left++;
      continue;
    }
    if (t?.match(HEAD)?.[1] === sha(body) && t.replace(HEAD, "") === body) continue;
    const head = `<!-- generated by ai-kit ${version} from conventions/${n}, never edit; sha256 ${sha(body)} -->\n\n`;
    writeFileSync(p, head + body);
    console.log(`~ ai/kit/conventions/${n}`);
  }
  for (const f of generated(dir))
    if (!want.has(f)) {
      if (!intact(read(join(dir, f)))) {
        console.log(`! ai/kit/conventions/${f} no longer applies and was edited by hand: left as it is`);
        left++;
        continue;
      }
      rmSync(join(dir, f));
      console.log(`- ai/kit/conventions/${f}`);
    }
  if (read(join(root, "ai", "kit", "check.sh")) !== CHECK_SH) {
    writeFileSync(join(root, "ai", "kit", "check.sh"), CHECK_SH);
    console.log("~ ai/kit/check.sh");
  }
  const cp = join(root, "CLAUDE.md");
  const claude = read(cp);
  if (!hasLine(claude)) {
    const raw = existsSync(cp) ? readFileSync(cp, "utf8") : "";
    const eol = raw.includes("\r\n") ? "\r\n" : "\n";
    writeFileSync(cp, `${raw}${raw && !raw.endsWith("\n") ? eol : ""}${raw ? eol : ""}${LINE}${eol}`);
    console.log("~ CLAUDE.md");
  }
  return left;
}

export function snapshotWarnings(root, kit) {
  const conf = config(root);
  if (conf?.unattended !== undefined && typeof conf.unattended !== "boolean")
    return ["ai/kit/config.json unattended must be true or false (fix: write it as true, or remove it)"];
  if (conf?.unattended !== true) return [];
  const out = [];
  const dir = join(root, "ai", "kit", "conventions");
  const want = bodies(root, kit);
  for (const [n, body] of want) {
    const t = read(join(dir, n));
    const name = `ai/kit/conventions/${n}`;
    if (t === null) out.push(`${name} is missing (${SYNC})`);
    else if (!HEAD.test(t)) out.push(`${name} is not a generated copy (fix: move it out, then run kit.mjs sync)`);
    else if (!intact(t)) out.push(`${name} was edited by hand (${SYNC}, which replaces it)`);
    else if (t.replace(HEAD, "") !== body) out.push(`${name} is stale against the plugin (${SYNC})`);
  }
  for (const f of generated(dir))
    if (!want.has(f)) out.push(`ai/kit/conventions/${f} no longer applies to this project (${SYNC}, or delete it when edited by hand)`);
  if (read(join(root, "ai", "kit", "check.sh")) !== CHECK_SH) out.push(`ai/kit/check.sh is missing or changed (${SYNC})`);
  if (!hasLine(read(join(root, "CLAUDE.md")))) out.push(`CLAUDE.md does not point to ai/kit/conventions/ (${SYNC})`);
  if (!read(join(root, ".githooks", "pre-commit"))?.includes("AI_KIT_RANGE="))
    out.push(".githooks/pre-commit is an older shim: $AI_KIT_RANGE is empty there, so a check on it reads the work tree at commit (fix: kit.mjs init)");
  const pc = read(join(root, "ai", "kit", "pre-commit.sh"));
  if (pc === null) return [...out, "ai/kit/pre-commit.sh is missing, so ai/kit/check.sh refuses to run (fix: kit.mjs init)"];
  const lines = pc.split("\n").filter((l) => !/^\s*#/.test(l));
  const code = lines.join("\n");
  if (lines.some((l) => new RegExp(STAGED).test(l)))
    out.push(
      "ai/kit/pre-commit.sh reads the staged diff, so ai/kit/check.sh refuses to run (fix: use changed and $AI_KIT_RANGE, as the plugin's templates/ai-kit-project/pre-commit.sh shows)",
    );
  else if (!code.trim()) out.push("ai/kit/pre-commit.sh has no checks, so ai/kit/check.sh passes whatever changed (fix: add the project's checks)");
  return out;
}
