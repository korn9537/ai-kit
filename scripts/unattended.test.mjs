// Tests for the unattended snapshot: kit.mjs sync and check, and ai/kit/check.sh, killed mid-run included.
// Usage: node scripts/unattended.test.mjs
import { execFileSync, spawn, spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { setTimeout as wait } from "node:timers/promises";

const SCRIPT = join(import.meta.dirname, "kit.mjs");
const TEMPLATE = join(import.meta.dirname, "..", "templates", "ai-kit-project", "pre-commit.sh");
let passed = 0;
let failed = 0;
function eq(desc, got, want) {
  const g = JSON.stringify(got);
  const w = JSON.stringify(want);
  if (g === w) {
    passed++;
    console.log(`ok   - ${desc}`);
  } else {
    failed++;
    console.log(`FAIL - ${desc}\n  got:  ${g}\n  want: ${w}`);
  }
}
const tmp = realpathSync(mkdtempSync(join(tmpdir(), "unattended-")));
const repo = join(tmp, "repo");
const kitCmd = (cmd) =>
  spawnSync("node", [SCRIPT, cmd], { cwd: repo, encoding: "utf8", env: { ...process.env, HOME: repo, CLAUDE_CONFIG_DIR: "" } }).stdout;
const git = (...a) => execFileSync("git", a, { cwd: repo, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
const at = (...p) => join(repo, ...p);
const config = (o) => writeFileSync(at("ai", "kit", "config.json"), JSON.stringify(o));
const check = (base) => spawnSync("sh", ["ai/kit/check.sh", base], { cwd: repo, encoding: "utf8" });
const commit = (m) => {
  git("add", "-A");
  git("-c", "core.hooksPath=/dev/null", "-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", m);
};
// the index by what it stages and its flags: its file also caches stat data, which any git status may refresh
const state = () => [git("rev-parse", "HEAD"), git("status", "--porcelain"), git("ls-files", "-s", "-v")];
// a project check in the template's shape: fails when a changed file is named bad
const projectCheck = () =>
  writeFileSync(
    at("ai", "kit", "pre-commit.sh"),
    `${readFileSync(TEMPLATE, "utf8")}if changed | grep -q 'bad'; then echo "project check failed"; exit 1; fi\n`,
  );

try {
  execFileSync("git", ["init", "-q", repo]);
  mkdirSync(at("ai", "kit"), { recursive: true });

  config({ conventions: ["nestjs"] });
  eq("sync: off without the key", kitCmd("sync").trim(), "unattended is off");
  eq("sync: off writes nothing", existsSync(at("ai", "kit", "conventions")), false);
  eq("check: off warns of nothing", kitCmd("check").includes("conventions/general.md"), false);

  config({ conventions: ["nestjs"], unattended: true });
  writeFileSync(at("CLAUDE.md"), "# Project\n");
  eq("check: on and not synced is warned", kitCmd("check").includes("ai/kit/conventions/general.md is missing"), true);
  kitCmd("sync");
  const copy = (n) => at("ai", "kit", "conventions", n);
  eq("sync: nestjs brings what it adds to", ["general.md", "nestjs.md", "typescript.md"].map((n) => existsSync(copy(n))), [true, true, true]);
  eq("sync: a language not asked for stays out", existsSync(copy("go.md")), false);
  const general = readFileSync(copy("general.md"), "utf8");
  eq("sync: the header names version and hand edits", /^<!-- generated by ai-kit \d+\.\d+\.\d+ from conventions\/general\.md, never edit;/.test(general), true);
  eq("sync: a plugin doc keeps the kit's name", general.includes("`ai-kit/docs/screen-specs.md`"), true);
  eq("sync: CLAUDE.md gains the pointer", readFileSync(at("CLAUDE.md"), "utf8"), "# Project\n\nBefore writing code, read `ai/kit/conventions/`.\n");
  kitCmd("sync");
  eq("sync: a second run adds no second pointer", readFileSync(at("CLAUDE.md"), "utf8").split("Before writing").length, 2);
  const warned = (t) => kitCmd("check").includes(t);
  git("add", "ai/kit/conventions");
  const docs = join(import.meta.dirname, "check-docs.mjs");
  eq("check-docs: the generated copies are out of scope", spawnSync("node", [docs, "--staged", "--strict"], { cwd: repo }).status, 0);
  git("reset", "-q");
  eq("check: synced warns of nothing", kitCmd("check").match(/ai\/kit\/(conventions\/|check\.sh is)|CLAUDE\.md does not/g), null);

  writeFileSync(copy("general.md"), `${general}extra\n`);
  eq("check: a hand edit is named", warned("general.md was edited by hand"), true);
  writeFileSync(copy("general.md"), general.replace(/sha256 [0-9a-f]{64}/, `sha256 ${"0".repeat(64)}`));
  eq("check: a changed hash reads as a hand edit", warned("general.md was edited by hand"), true);
  kitCmd("sync");
  eq("sync: a hand edit is replaced", readFileSync(copy("general.md"), "utf8"), general);
  const body = general.replace(/^.*\n\n/, "").replace("# General", "# Older");
  const { createHash } = await import("node:crypto");
  const hash = createHash("sha256").update(body).digest("hex");
  writeFileSync(copy("general.md"), `<!-- generated by ai-kit 1.0.0 from conventions/general.md, never edit; sha256 ${hash} -->\n\n${body}`);
  eq("check: an older copy is stale, not edited", warned("general.md is stale against the plugin"), true);
  kitCmd("sync");
  const older = general.replace(/ai-kit \S+ from/, "ai-kit 1.0.0 from");
  writeFileSync(copy("general.md"), older);
  eq("check: a new version alone is not stale", warned("general.md is stale"), false);
  kitCmd("sync");
  eq("sync: a new version alone rewrites nothing", readFileSync(copy("general.md"), "utf8"), older);
  config({ conventions: [], unattended: true });
  eq("check: a language dropped from config is named", warned("nestjs.md no longer applies"), true);
  kitCmd("sync");
  eq("sync: a generated copy that no longer applies goes", existsSync(copy("nestjs.md")), false);
  mkdirSync(copy("sub"));
  writeFileSync(copy("go.md"), "my own notes\n");
  config({ conventions: ["go"], unattended: true });
  eq("check: a subfolder is no crash, a file of the project's own is named", warned("go.md is not a generated copy"), true);
  eq("sync: a file left is said, not reported as in sync", kitCmd("sync").trim().split("\n").pop(), "1 file(s) left, see above");
  eq("sync: a file of the project's own is left", readFileSync(copy("go.md"), "utf8"), "my own notes\n");
  rmSync(copy("go.md"));
  rmSync(copy("sub"), { recursive: true });
  config({ conventions: ["nestjs"], unattended: true });
  kitCmd("sync");
  const edited = `${readFileSync(copy("nestjs.md"), "utf8")}my line\n`;
  writeFileSync(copy("nestjs.md"), edited);
  config({ conventions: [], unattended: true });
  kitCmd("sync");
  eq("sync: a hand-edited copy that no longer applies is left", readFileSync(copy("nestjs.md"), "utf8"), edited);
  rmSync(copy("nestjs.md"));
  config({ conventions: [], unattended: "yes" });
  eq("check: a non-boolean key is named", warned("unattended must be true or false"), true);
  config({ conventions: [], unattended: true });

  eq("check: a missing pre-commit.sh is named as missing", warned("pre-commit.sh is missing"), true);
  mkdirSync(at(".githooks"), { recursive: true });
  writeFileSync(at(".githooks", "pre-commit"), "# ai-kit shim, older\n");
  eq("check: an older shim is named", warned("is an older shim"), true);
  writeFileSync(at(".githooks", "pre-commit"), "# ai-kit shim, older\nchanged() { :; }\n");
  eq("check: a shim with changed but no range is named", warned("is an older shim"), true);
  rmSync(at(".githooks"), { recursive: true });
  const { HELPERS } = await import("./unattended.mjs");
  const helper = HELPERS.slice(HELPERS.indexOf("changed() {"));
  eq("hook: its changed is the runners' changed", readFileSync(join(import.meta.dirname, "..", "githooks", "pre-commit"), "utf8").includes(helper), true);
  const gate = "if git diff --cached --name-only | grep -q bad; then exit 1; fi\n";
  writeFileSync(at("ai", "kit", "pre-commit.sh"), gate);
  eq("check: a staged-only pre-commit.sh is named", warned("reads the staged diff"), true);
  commit("base");
  eq("check.sh: a staged-only pre-commit.sh is refused, never passed", check("HEAD").status, 1);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), `if changed | grep -q x; then exit 1; fi\n${gate}`);
  eq("check.sh: one gate left on staged files is refused", check("HEAD").status, 1);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), gate.replace("--cached", "--staged"));
  eq("check.sh: --staged is refused too", check("HEAD").status, 1);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), "git --literal-pathspecs diff --cached -U0 -- x | grep -q bad && exit 1\n");
  eq("check.sh: a diff of added lines on the index is refused", check("HEAD").status, 1);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), "git grep -q --cached -e nothing-here -- x || true\n");
  eq("check.sh: an index read that is no diff runs", check("HEAD").status, 0);
  eq("check: an index read that is no diff is not named", warned("reads the staged diff"), false);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), `${gate.replace("--cached", "$AI_KIT_RANGE")}node scripts/x.mjs --staged --strict\n`);
  eq("check.sh: --staged passed to a script is refused", check("HEAD").status, 1);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), `# AI_KIT_FILES\n${gate}`);
  eq("check.sh: a comment does not lift the refusal", check("HEAD").status, 1);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), "if changed | grep -q bad; then\n");
  eq("check.sh: a script that does not parse fails", check("HEAD").status, 1);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), "# nothing yet\n");
  eq("check: a pre-commit.sh with no checks is named", warned("has no checks"), true);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), `sh -c '[ -z "\${AI_KIT_FILES+set}" ]' || exit 1\n`);
  eq("check.sh: the list stays out of the environment of what it runs", check("HEAD").status, 0);

  projectCheck();
  commit("project check");
  const base = git("rev-parse", "HEAD");
  writeFileSync(at("good.txt"), "x\n");
  commit("good");
  const clean = check(base);
  eq("check.sh: a clean range passes and says what it covered", [clean.status, clean.stdout.trim()], [0, `checked 1 file(s) from ${base}`]);
  writeFileSync(at("bad.txt"), "x\n");
  commit("bad");
  const before = state();
  const added = (c) => `${readFileSync(TEMPLATE, "utf8")}if git diff $AI_KIT_RANGE ${c} | grep -qE '^\\+x'; then echo "added x"; exit 1; fi\n`;
  const saved = readFileSync(at("ai", "kit", "pre-commit.sh"));
  writeFileSync(at("ai", "kit", "pre-commit.sh"), added("-U0 -- bad.txt"));
  const inRange = check(base);
  eq("check.sh: $AI_KIT_RANGE reads the added lines of the range", [inRange.status, inRange.stdout.trim()], [1, "added x"]);
  eq("check.sh: $AI_KIT_RANGE stops at the base", check("HEAD").status, 0);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), `sh -c 'git diff $AI_KIT_RANGE -U0 -- bad.txt' | grep -qE '^\\+x' && exit 1\n`);
  eq("check.sh: a child process reads $AI_KIT_RANGE", check(base).status, 1);
  eq("check.sh: a base with a space is refused, never passed", check("HEAD@{1 minute ago}").status, 2);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), saved);
  const r = check(base);
  eq("check.sh: a bad file in the range fails", [r.status, r.stdout.trim()], [1, "project check failed"]);
  eq("check.sh: HEAD, status and index are untouched", state(), before);
  eq("check.sh: an unknown base fails, never passes", check("no-such-ref").status, 1);
  eq("check.sh: no base is a usage error", spawnSync("sh", ["ai/kit/check.sh"], { cwd: repo }).status, 2);
  eq("check.sh: an empty range ignores staged files", (() => {
    writeFileSync(at("bad2.txt"), "x\n");
    git("add", "bad2.txt");
    const s = check("HEAD").status;
    git("reset", "-q", "--", "bad2.txt");
    rmSync(at("bad2.txt"));
    return s;
  })(), 0);
  const HOOK = join(import.meta.dirname, "..", "githooks", "pre-commit");
  const staged = (hook, name) => {
    writeFileSync(at(name), "x\n");
    git("add", name);
    const s = spawnSync("sh", [hook], { cwd: repo, encoding: "utf8" }).status;
    git("reset", "-q", "--", name);
    rmSync(at(name));
    return s;
  };
  eq("hook: changed gives the staged files, a bad one fails", staged(HOOK, "bad3.txt"), 1);
  eq("hook: changed gives the staged files, a good one passes", staged(HOOK, "fine.txt"), 0);
  const gated = readFileSync(at("ai", "kit", "pre-commit.sh"));
  writeFileSync(at("ai", "kit", "pre-commit.sh"), `git diff $AI_KIT_RANGE --name-only | grep -q 'worse' && exit 1\n`);
  eq("hook: $AI_KIT_RANGE is the staged diff, a bad one fails", staged(HOOK, "worse.txt"), 1);
  eq("hook: $AI_KIT_RANGE is the staged diff, a good one passes", staged(HOOK, "fine.txt"), 0);
  writeFileSync(at("ai", "kit", "pre-commit.sh"), gated);
  kitCmd("init");
  rmSync(at(".git", "ai-kit-root"));
  eq("shim with no plugin: a bad staged file fails", staged(".githooks/pre-commit", "bad4.txt"), 1);
  eq("shim with no plugin: a good staged file passes", staged(".githooks/pre-commit", "fine.txt"), 0);
  commit("wired");

  // killed mid-run: the check is inside pre-commit.sh when SIGKILL lands, so no trap or cleanup can run
  copyFileSync(at("ai", "kit", "pre-commit.sh"), join(tmp, "pc"));
  writeFileSync(at("ai", "kit", "pre-commit.sh"), `${readFileSync(TEMPLATE, "utf8")}: >"${join(tmp, "started")}"\nsleep 30\n`);
  commit("slow check");
  const held = state();
  const child = spawn("sh", ["ai/kit/check.sh", base], { cwd: repo, stdio: "ignore", detached: true });
  const gone = new Promise((res) => child.on("exit", (code, sig) => res(sig)));
  for (let i = 0; i < 100 && !existsSync(join(tmp, "started")); i++) await wait(50);
  eq("kill: the run reached the project check", existsSync(join(tmp, "started")), true);
  process.kill(-child.pid, "SIGKILL");
  eq("kill: the run died of SIGKILL", await gone, "SIGKILL");
  eq("kill: HEAD, status and index are as they were", state(), held);
  copyFileSync(join(tmp, "pc"), at("ai", "kit", "pre-commit.sh"));
  eq("kill: the next run works", check(base).status, 1);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

console.log(`${passed} passed, ${failed} failed`);
process.exitCode = failed ? 1 : 0;
