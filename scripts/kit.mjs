// null when the project has not opted in, else how many files it left; a current copy stays, whatever kit wrote it
function syncSnapshot(root, kit, conf) {
  if (conf?.unattended !== true) return null;
  let left = 0;
  const version = JSON.parse(readLF(join(kit, ".claude-plugin", "plugin.json"))).version;
  const dir = join(root, "ai", "kit", "conventions");
  mkdirSync(dir, { recursive: true });
  const want = bodies(kit, conf);
  for (const [n, body] of want) {
    const p = join(dir, n);
    const t = readLF(p);
    if (t !== null && !HEAD.test(t)) {
      console.log(`! ai/kit/conventions/${n} is not a generated copy: left as it is`);
      left++;
      continue;
    }
    if (t?.match(HEAD)?.[1] === sha(body) && t.replace(HEAD, "") === body) continue;
    writeFileSync(p, headOf(version, `conventions/${n}`, "md", body) + body);
    console.log(`~ ai/kit/conventions/${n}`);
  }
  for (const f of generated(dir))
    if (!want.has(f)) {
      if (!intact(readLF(join(dir, f)))) {
        console.log(`! ai/kit/conventions/${f} no longer applies and was edited by hand: left as it is`);
        left++;
        continue;
      }
      rmSync(join(dir, f));
      console.log(`- ai/kit/conventions/${f}`);
    }
  for (const [rel, [src, style, body]] of extras(kit)) {
    const p = join(root, rel);
    const t = readLF(p);
    if (t !== null && !HEAD.test(t)) {
      console.log(`! ${rel} is not a generated copy: left as it is`);
      left++;
      continue;
    }
    if (t?.match(HEAD)?.[1] === sha(body) && t.replace(HEAD, "") === body) continue;
    mkdirSync(join(p, ".."), { recursive: true });
    writeFileSync(p, headOf(version, src, style, body) + body);
    console.log(`~ ${rel}`);
  }
  const req = join(root, "ai", "kit", "requires.txt");
  if (!existsSync(req)) {
    const tools = toolsIn(codeLines(readLF(join(root, "ai", "kit", "pre-commit.sh")) ?? "").join("\n"));
    writeFileSync(req, `# Commands ai/kit/pre-commit.sh needs, one per line; ai/kit/check.sh stops when one is missing.\n${tools.map((x) => `${x}\n`).join("")}`);
    console.log(`~ ai/kit/requires.txt: ${tools.join(" ") || "no known command"}; a start, add what it does not know`);
  }
  if (readLF(join(root, "ai", "kit", "check.sh")) !== CHECK_SH) {
    writeFileSync(join(root, "ai", "kit", "check.sh"), CHECK_SH);
    console.log("~ ai/kit/check.sh");
  }
  const cp = join(root, "CLAUDE.md");
  const claude = readLF(cp);
  if (!hasLine(claude)) {
    const raw = existsSync(cp) ? readFileSync(cp, "utf8") : "";
    const eol = raw.includes("\r\n") ? "\r\n" : "\n";
    writeFileSync(cp, `${raw}${raw && !raw.endsWith("\n") ? eol : ""}${raw ? eol : ""}${LINE}${eol}`);
    console.log("~ CLAUDE.md");
  }
  return left;
}

const codeLines = (text) => text.split("\n").filter((l) => !/^\s*#/.test(l));

function snapshotWarnings(root, kit, conf) {
  if (conf?.unattended !== undefined && typeof conf.unattended !== "boolean")
    return ["ai/kit/config.json unattended must be true or false (fix: write it as true, or remove it)"];
  if (conf?.unattended !== true) {
    const off = readLF(join(root, "ai", "kit", "pre-commit.sh"));
    return off !== null && codeLines(off).some((l) => new RegExp(STAGED).test(l))
      ? ["ai/kit/pre-commit.sh reads the staged diff, which no gate can run (fix: kit.mjs unattended --dry-run shows what to change)"]
      : [];
  }
  const out = [];
  const dir = join(root, "ai", "kit", "conventions");
  const want = bodies(kit, conf);
  for (const [n, body] of want) {
    const t = readLF(join(dir, n));
    const name = `ai/kit/conventions/${n}`;
    if (t === null) out.push(`${name} is missing (${SYNC})`);
    else if (!HEAD.test(t)) out.push(`${name} is not a generated copy (fix: move it out, then run kit.mjs sync)`);
    else if (!intact(t)) out.push(`${name} was edited by hand (${SYNC}, which replaces it)`);
    else if (t.replace(HEAD, "") !== body) out.push(`${name} is stale against the plugin (${SYNC})`);
  }
  for (const f of generated(dir))
    if (!want.has(f)) out.push(`ai/kit/conventions/${f} no longer applies to this project (${SYNC}, or delete it when edited by hand)`);
  for (const [rel, [, , body]] of extras(kit)) {
    const t = readLF(join(root, rel));
    if (t === null) out.push(`${rel} is missing (${SYNC})`);
    else if (!HEAD.test(t)) out.push(`${rel} is not a generated copy (fix: move it out, then run kit.mjs sync)`);
    else if (!intact(t)) out.push(`${rel} was edited by hand (${SYNC}, which replaces it)`);
    else if (t.replace(HEAD, "") !== body) out.push(`${rel} is stale against the plugin (${SYNC})`);
  }
  // an ignored copy works here and is absent from every clone, where check.sh then fails each run
  for (const rel of ["ai/kit/check.sh", "ai/kit/requires.txt", ...extras(kit).keys()])
    if (tryGitIn(root, ["check-ignore", "-q", "--no-index", rel]) !== null)
      out.push(`${rel} is ignored by git, so a clone will not have it (fix: add !${rel} to .gitignore)`);
  if (readLF(join(root, "ai", "kit", "check.sh")) !== CHECK_SH) out.push(`ai/kit/check.sh is missing or changed (${SYNC})`);
  if (readLF(join(root, "ai", "kit", "requires.txt")) === null)
    out.push(`ai/kit/requires.txt is missing, so ai/kit/check.sh refuses to run (${SYNC}, then add what it does not know)`);
  if (!hasLine(readLF(join(root, "CLAUDE.md")))) out.push(`CLAUDE.md does not point to ai/kit/conventions/ (${SYNC})`);
  if (!readLF(join(root, ".githooks", "pre-commit"))?.includes("AI_KIT_RANGE="))
    out.push(".githooks/pre-commit is an older shim: $AI_KIT_RANGE is empty there, so a check on it reads the work tree at commit (fix: kit.mjs init)");
  const pc = readLF(join(root, "ai", "kit", "pre-commit.sh"));
  if (pc === null) return [...out, "ai/kit/pre-commit.sh is missing, so ai/kit/check.sh refuses to run (fix: kit.mjs init)"];
  const lines = codeLines(pc);
  const code = lines.join("\n");
  if (lines.some((l) => new RegExp(STAGED).test(l)))
    out.push(
      "ai/kit/pre-commit.sh reads the staged diff, so ai/kit/check.sh refuses to run (fix: kit.mjs unattended rewrites what it can; else use changed and $AI_KIT_RANGE, as the plugin's templates/ai-kit-project/pre-commit.sh shows)",
    );
  else if (!code.trim()) out.push("ai/kit/pre-commit.sh has no checks, so ai/kit/check.sh passes whatever changed (fix: add the project's checks)");
  return out;
}


