const LINE = "Before writing code, read `ai/kit/conventions/`.";

const HEAD = /^(?:<!--|\/\/) generated by ai-kit \S+ from \S+, never edit; sha256 ([0-9a-f]{64})(?: -->)?\n\n/;

const SYNC = "fix: node <plugin>/scripts/kit.mjs sync";

// a diff of the index finds nothing under check.sh, and --staged asks a script for that diff; other index reads hold,
// a clean clone's index being HEAD
const STAGED = "diff[^|;&]*--cached|--staged";

// what ai/kit/pre-commit.sh may call, in every runner that sources it; githooks/pre-commit holds the same
export const HELPERS = `quiet() {
  out=$("$@" 2>&1); rc=$?
  if [ $rc -ne 0 ]; then printf '%s\\n' "$out"
  else
    n=$(printf '%s\\n' "$out" | grep -c '^!')
    [ "$n" -gt 0 ] && echo "warn: $n warning(s) from: $* (run it alone for details)"
  fi
  return $rc
}
# the files to check: AI_KIT_FILES when ai/kit/check.sh set it, else the staged ones
changed() {
  if [ -n "\${AI_KIT_FILES+set}" ]; then [ -z "$AI_KIT_FILES" ] || printf '%s\\n' "$AI_KIT_FILES"
  else git diff --cached --name-only --diff-filter=ACMR; fi
}
# what a check that reads the diff passes to git diff, unquoted; ai/kit/check.sh replaces it with its range
export AI_KIT_RANGE=--cached
`;

const sha = (t) => createHash("sha256").update(t).digest("hex");

const readLF = (p) => read(p)?.replace(/\r\n/g, "\n") ?? null;

const codeLines = (text) => text.split("\n").filter((l) => !/^\s*#/.test(l));

const kit = join(import.meta.dirname, "..", "..");

const PLUGIN = "ai-kit@korn9537";

const MARK = "ai-kit-root";

// the recorded path, or when a plugin update removed that version, the newest x.y.z beside it
const RESOLVE = (hook) => `kit="$(cat "$(git rev-parse --path-format=absolute --git-common-dir)/${MARK}" 2>/dev/null)"
if [ -n "$kit" ] && [ ! -f "$kit/githooks/${hook}" ]; then
  base="$(dirname "$kit")"
  kit="$(ls "$base" 2>/dev/null | grep -E '^[0-9]+\\.[0-9]+\\.[0-9]+$' |
    awk -F. '{ printf "%06d%06d%06d %s\\n", $1, $2, $3, $0 }' | sort | tail -n 1 | cut -d' ' -f2)"
  [ -n "$kit" ] && kit="$base/$kit"
fi
`;

const SHIM = `#!/usr/bin/env sh
# ai-kit shim (core.hooksPath): runs the plugin's githooks/pre-commit; session-start.sh records its path.
${RESOLVE("pre-commit")}if [ -n "$kit" ] && [ -f "$kit/githooks/pre-commit" ]; then
  exec sh "$kit/githooks/pre-commit" "$@"
fi
echo "warn: ai-kit plugin path unknown: open Claude Code in this repo once"

cd "$(git rev-parse --show-toplevel)" || exit 1
# same helpers as the plugin's githooks/pre-commit, which ai/kit/pre-commit.sh may call
${HELPERS}# shellcheck source=/dev/null
[ -f ai/kit/pre-commit.sh ] && . ai/kit/pre-commit.sh
exit 0
`;

const MSG_SHIM = `#!/usr/bin/env sh
# ai-kit shim (core.hooksPath): runs the plugin's githooks/commit-msg; session-start.sh records its path.
${RESOLVE("commit-msg")}if [ -n "$kit" ] && [ -f "$kit/githooks/commit-msg" ]; then
  exec sh "$kit/githooks/commit-msg" "$@"
fi
echo "warn: ai-kit plugin path unknown, Job trailer not checked: open Claude Code in this repo once" >&2
exit 0
`;

// every call runs at the repo top, so pathspecs and output are root-relative from a subdirectory too
const gitIn = (cwd, a) =>
  execFileSync("git", a, {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
    // ls-files of a large repo is several MB; over the buffer the call fails and reads as empty
    maxBuffer: 1 << 30,
  }).trim();

const tryGitIn = (cwd, a) => {
  try {
    return gitIn(cwd, a);
  } catch {
    return null;
  }
};

// the git top: core.hooksPath resolves from there, and the shims and check.sh cd to it, so ai/kit must sit there
const root = tryGitIn(process.cwd(), ["rev-parse", "--show-toplevel"]) ?? process.cwd();

const tryGit = (...a) => tryGitIn(root, a);

// core.hooksPath is relative to the repo top; an absolute path to the repo's own .githooks is the same directory
const ownHooksPath = (hp) => {
  if (hp === ".githooks") return true;
  if (!hp) return false;
  const real = (p) => {
    try {
      return realpathSync(p);
    } catch {
      return resolve(p);
    }
  };
  return real(resolve(root, hp)) === real(join(root, ".githooks"));
};

const at = (...p) => join(root, ...p);

const read = (p) => (existsSync(p) ? readFileSync(p, "utf8") : null);

// ai/kit/config.json read once per command, then handed to each check: its text (null when missing), the value (null
// when missing, undefined when it is not JSON) and the parse error
const readConf = () => {
  const text = read(at("ai", "kit", "config.json"));
  if (text === null) return { text, conf: null };
  try {
    return { text, conf: JSON.parse(text) };
  } catch (error) {
    return { text, error };
  }
};

const shimPath = at(".githooks", "pre-commit");

const msgShimPath = at(".githooks", "commit-msg");

const isShim = (s) => s?.includes(MARK) ?? false;

// a hook git cannot run is skipped silently; Windows has no execute bit to read
const notExecutable = (p) => process.platform !== "win32" && (statSync(p).mode & 0o111) === 0;

const claudeDir = () => process.env.CLAUDE_CONFIG_DIR || join(homedir(), ".claude");

// warnings, not problems: this machine's state, and a project before 2.7.0 must keep committing
// sh and bash read these with LF only; Git for Windows (core.autocrlf) checks text out as CRLF without an eol rule
const LF_RULES = [
  { line: ".githooks/* text eol=lf", sample: ".githooks/pre-commit" },
  { line: "ai/kit/*.sh text eol=lf", sample: "ai/kit/pre-commit.sh" },
];

const lfMissing = () =>
  LF_RULES.filter((r) => !/: eol: lf$/m.test(tryGit("check-attr", "eol", "--", r.sample) ?? ""));

const eolOf = (t) => (t.includes("\r\n") ? "\r\n" : "\n");

const dropEcho = (s) => s.replace(/\becho\s+("(?:[^"\\]|\\.)*"|'[^']*')/g, "").split("\n").filter((l) => !/^\s*echo\b/.test(l)).join("\n");

const TOOLS = "node npx pnpm npm yarn bun go gofmt golangci-lint dotnet python python3 ruby php dart flutter cargo java mvn gradle jq curl shellcheck rg sqlc";

const toolsIn = (code) => {
  const text = dropEcho(code);
  return TOOLS.split(" ").filter((x) => new RegExp(`(^|[\\s(|;&"'])${x}(?=\\s|$|[)|;&"'])`, "m").test(text));
};

const jsonText = (o, eol) =>
  `${JSON.stringify(o, null, 2).replace(/\n/g, eol)}${eol}`;

const isObj = (o) => o !== null && typeof o === "object" && !Array.isArray(o);

const lsFiles = (...a) =>
  (tryGit("ls-files", "-z", ...a) ?? "").split("\0").filter(Boolean);

export { HEAD, LINE, MARK, MSG_SHIM, PLUGIN, SHIM, STAGED, SYNC, at, claudeDir, codeLines, dropEcho, eolOf, isObj, isShim, jsonText, kit, lfMissing, lsFiles, msgShimPath, notExecutable, ownHooksPath, read, readConf, readLF, root, sha, shimPath, toolsIn, tryGit, tryGitIn };
